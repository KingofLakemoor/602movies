document.addEventListener('DOMContentLoaded', () => {
    const form = document.getElementById('review-form');
    const reviewTextarea = document.getElementById('review');
    const charCountDisplay = document.getElementById('char-count');
    const messageDiv = document.getElementById('message');
    const reviewsList = document.getElementById('reviews-list');

    // Update character count
    reviewTextarea.addEventListener('input', () => {
        const remaining = 300 - reviewTextarea.value.length;
        charCountDisplay.textContent = `${remaining} characters remaining`;
    });

    const fetchReviews = async () => {
        try {
            // Here we could filter by movieId if we wanted to only show the current movie's reviews,
            // but for now we'll fetch all and display the Movie ID to show they are grouped/stored.
            const response = await fetch('/reviews');
            const data = await response.json();

            reviewsList.innerHTML = '';

            if (data.length === 0) {
                reviewsList.innerHTML = '<p>No reviews yet.</p>';
                return;
            }

            // Display reviews in reverse order (newest first)
            data.slice().reverse().forEach(review => {
                const reviewItem = document.createElement('div');
                reviewItem.classList.add('review-item');

                let starsHTML = '';
                for (let i = 1; i <= 5; i++) {
                    if (review.rating >= i) {
                        starsHTML += '★';
                    } else if (review.rating >= i - 0.5) {
                        starsHTML += '⯪'; // half star
                    } else {
                        starsHTML += '☆';
                    }
                }

                const headerDiv = document.createElement('div');
                headerDiv.classList.add('review-header');

                const usernameSpan = document.createElement('span');
                usernameSpan.classList.add('review-username');
                // Display username and movie ID
                usernameSpan.textContent = `${review.username} (Movie: ${review.movieId})`;

                const ratingSpan = document.createElement('span');
                ratingSpan.classList.add('review-rating');
                ratingSpan.innerHTML = starsHTML; // Safe, generated by our logic

                headerDiv.appendChild(usernameSpan);
                headerDiv.appendChild(ratingSpan);

                const textDiv = document.createElement('div');
                textDiv.classList.add('review-text');
                textDiv.textContent = review.review;

                reviewItem.appendChild(headerDiv);
                reviewItem.appendChild(textDiv);

                reviewsList.appendChild(reviewItem);
            });
        } catch (error) {
            console.error('Error fetching reviews:', error);
        }
    };

    // Initial fetch
    fetchReviews();

    form.addEventListener('submit', async (e) => {
        e.preventDefault();

        const formData = new FormData(form);
        const data = {
            username: formData.get('username'),
            movieId: formData.get('movieId'),
            rating: formData.get('rating') ? parseFloat(formData.get('rating')) : 0,
            review: formData.get('review')
        };

        try {
            const response = await fetch('/submit-review', {
                method: 'POST',
                headers: {
                    'Content-Type': 'application/json'
                },
                body: JSON.stringify(data)
            });

            if (response.ok) {
                const resultText = await response.text();
                messageDiv.textContent = resultText;
                messageDiv.className = 'success';
                form.reset();
                charCountDisplay.textContent = '300 characters remaining';
                fetchReviews(); // Refresh list
            } else {
                const errorText = await response.text();
                messageDiv.textContent = errorText;
                messageDiv.className = 'error';
            }
        } catch (error) {
            messageDiv.textContent = 'An error occurred while submitting the review.';
            messageDiv.className = 'error';
        }

        // Clear message after 3 seconds
        setTimeout(() => {
            messageDiv.textContent = '';
            messageDiv.className = '';
        }, 3000);
    });
});
